package com.bitsson.gensokyou.danmaku.render;

/**
 * 客户端弹幕实体所处的同步模式。
 *
 * <p><b>一个实体同一时刻 MUST 只有一种模式拥有模拟坐标的写权限。</b>两种模式并存
 * 等于有两个写入者，而两个写入者各自「看起来合理」时，症状是弹在半路上被两股力量
 * 拉向不同方向——既不是滞后也不是失步，无法归因。
 */
public enum DanmakuSyncMode {

    /**
     * 原版位置包驱动。
     *
     * <p>样本<b>只进诊断</b>：不参与渲染纠偏、不参与失步判定、不参与重建。
     *
     * <p>保留它是因为原版位置包没有服务器采样时间，一个位置点既无法区分
     * 「正常传输延迟」与「错误年龄基准」，也无法在曲射/编队弹上反推唯一相位。
     * 把它当权威数据用，等于把「空间误差」当成「时间误差」——那正是 {@code rerun}
     * 期间那批双峰翻转读数的来源。
     */
    LEGACY_POSITION,

    /**
     * 实体级快照 + 带时间标记的校准样本。
     *
     * <p>模拟坐标只被两件事改写：本地运动 tick，以及完整快照的原子应用。
     * 普通位置样本进入权威样本层，用于比对与视觉纠偏，不改模拟起点。
     */
    SNAPSHOT
}
