# gensokyo_terrain_blocks - 幻想乡维度大面积地形基底方块与16x16像素地表植被贴图
#
# 一、大面积铺设基底方块（7种，满格完全不透明）：
#   1. 幻想石 (gensokyo_stone)       - 替代原版石头：微带紫灰灵韵的层状岩石，与3种矿石底纹完美无缝融合
#   2. 幻想土 (gensokyo_dirt)        - 替代原版泥土：温润赭褐壤土，带自然小卵石与团粒结构，作为草径/腐殖土的底面
#   3. 幻想草径 (gensokyo_grass_block)- 替代原版草方块（顶面 top + 侧面 side，底面复用 gensokyo_dirt）：
#                                      青翠苍绿的灵茵草皮，侧面草帘自然垂落于幻想土上
#   4. 幻想沙 (gensokyo_sand)        - 替代原版沙子（三途川海岸/雾之湖滩）：冷调冥河苍灰细砂，柔和涟漪层理
#   5. 白玉岩 (hakugyoku_stone)      - 白玉楼阶状台地与守矢高岭：温润羊脂白玉岩，带淡青碧玉脉络与柔和云母光泽
#   6. 地底暗岩 (chireiden_deepslate)- 地灵殿裂谷与深层地下：厚重黑曜暗紫板岩，层叠劈理中隐现地底余温暗红微痕
#   7. 林间腐殖土 (forest_humus)     - 魔法森林与迷途竹林地表（顶面 top + 侧面 side，底面复用 gensokyo_dirt）：
#                                      幽紫褐落叶菌丝腐殖层，散布翠竹枯叶与微光菌丝斑
#
# 二、16x16 像素地表植被方块（4种，透明底 cutout）：
#   8. 幻想灵茵 (gensokyo_short_grass)- cross模型：错落摇曳的青翠灵草丛，叶尖带微青灵光
#   9. 冥界落樱瓣 (fallen_sakura_petals)- 贴地carpet/flowerbed模型：散落的白樱与淡粉花瓣簇
#  10. 幽光蕈簇 (glow_mushroom_cluster)- cross模型：大小错落的幽紫蓝发光小蘑菇群，伞盖带星点荧光孢子
#  11. 雾湖芦苇 (misty_reed)         - cross模型：挺拔的灰青水边芦苇与淡金白芦花穗

