# amp_core.py - 增幅核：金属托座（灰度染层，tint=品阶色）+ 灰度晶石（染层，tint=实例随机色）
# 模型双层：layer0=amp_core（托座，tintindex=0 → 品阶色），layer1=amp_core_dye（晶石，tintindex=1 → 随机色）
# 两层均为灰度纪律：高光近白、阴影近黑，乘法 tint 后呈现目标色明暗层次

TEXES = {}

def _sym(left):
    """左半 8 字符 → 左右镜像 16 宽整行。"""
    assert len(left) == 8, "left half must be 8 chars"
    return left + left[::-1]

# ---- 金属托座：八角轮廓 + 铜铆钉 + 中央 6×6 镶座孔（孔区透明，露出染层） ----
TEXES["item/amp_core"] = [
    _sym("....kkkk"),      # 0
    _sym("...kkgGG"),      # 1
    _sym("..kkgGGG"),      # 2
    _sym(".kkgGGGG"),      # 3
    _sym(".kkgMGGG"),      # 4  铜铆钉
    _sym(".kkgk..."),      # 5  ┐
    _sym(".kkgk..."),      # 6  │
    _sym(".kksk..."),      # 7  ├ 镶座孔（透明孔区，染层负责填充）
    _sym(".kksk..."),      # 8  │
    _sym(".kksk..."),      # 9  │
    _sym(".kksk..."),      # 10 ┘
    _sym(".kksMsss"),      # 11 铜铆钉（暗侧）
    _sym(".kksGGGG"),      # 12
    _sym("..kksGGG"),      # 13
    _sym("...kksGG"),      # 14
    _sym("....kkkk"),      # 15
]
